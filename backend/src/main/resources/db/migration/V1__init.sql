-- Plain SQL that runs on Postgres (prod) and on H2 in PostgreSQL mode (dev, tests).
-- Hibernate validates the entities against this schema at startup.

create table faculty (
    id                bigint generated by default as identity primary key,
    name              varchar(255) not null unique,
    short_code        varchar(10)  not null unique,
    color             varchar(255),
    emoji             varchar(255),
    members           integer,
    points            integer,
    territory_geojson varchar(10000)
);

create table street_segment (
    id                   bigint generated by default as identity primary key,
    name                 varchar(255) not null,
    district             varchar(255),
    center_lat           double precision,
    center_lng           double precision,
    ai_cleanliness_score double precision,
    recent_report_count  integer,
    last_evaluated_at    timestamp(6) with time zone,
    faculty_id           bigint references faculty (id)
);

create table hotspot (
    id                bigint generated by default as identity primary key,
    center_lat        double precision not null,
    center_lng        double precision not null,
    mean_cleanliness  double precision,
    report_count      integer,
    status            varchar(255) not null
        check (status in ('OPEN', 'ESCALATED', 'DISPATCHED', 'RESOLVED')),
    label             varchar(255),
    street_segment_id bigint references street_segment (id),
    created_at        timestamp(6) with time zone,
    last_updated_at   timestamp(6) with time zone
);

create table report (
    id                 bigint generated by default as identity primary key,
    lat                double precision not null,
    lng                double precision not null,
    cleanliness_score  integer not null,
    note               varchar(500),
    photo_url          varchar(1024),
    ai_description     varchar(200),
    source             varchar(16) not null check (source in ('WHATSAPP', 'WEB', 'DEMO')),
    signal_tags        varchar(200),
    reporter_pseudo_id varchar(255),
    faculty_id         bigint references faculty (id),
    hotspot_id         bigint references hotspot (id),
    reported_at        timestamp(6) with time zone not null
);

create index idx_report_geo on report (lat, lng);
create index idx_report_hotspot on report (hotspot_id);
create index idx_report_reported_at on report (reported_at);

create table work_order (
    id            bigint generated by default as identity primary key,
    planon_ref    varchar(255),
    hotspot_id    bigint not null references hotspot (id),
    status        varchar(255) not null
        check (status in ('PENDING', 'DISPATCHED', 'IN_PROGRESS', 'COMPLETED', 'FAILED')),
    priority      varchar(255) not null check (priority in ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    crew          varchar(255),
    summary       varchar(255),
    created_at    timestamp(6) with time zone,
    dispatched_at timestamp(6) with time zone,
    completed_at  timestamp(6) with time zone
);

create index idx_work_order_hotspot on work_order (hotspot_id);

create table stored_photo (
    id           varchar(36) primary key,
    content_type varchar(50) not null,
    bytes        bytea       not null,
    created_at   timestamp(6) with time zone not null
);

create table app_user (
    id                 bigint generated by default as identity primary key,
    email              varchar(254) not null unique,
    password_hash      varchar(72)  not null,
    faculty_short_code varchar(10),
    role               varchar(16)  not null check (role in ('USER', 'CREW')),
    points             integer default 0 not null,
    consent_given      boolean not null,
    consent_given_at   timestamp(6) with time zone,
    created_at         timestamp(6) with time zone not null,
    session_token_hash varchar(64) unique,
    session_expires_at timestamp(6) with time zone
);

create table reward_item (
    id          bigint generated by default as identity primary key,
    title       varchar(255) not null,
    description varchar(500),
    sponsor     varchar(255),
    category    varchar(255),
    image_ref   varchar(255),
    cost_points integer,
    stock       integer
);

create table redemption (
    id           bigint generated by default as identity primary key,
    user_id      bigint not null references app_user (id),
    reward_id    bigint not null references reward_item (id),
    voucher_code varchar(16) not null unique,
    cost_points  integer not null,
    redeemed_at  timestamp(6) with time zone not null
);

create index idx_redemption_user on redemption (user_id);

create table pending_report (
    id         bigint generated by default as identity primary key,
    sender_key varchar(64) not null unique,
    lat        double precision not null,
    lng        double precision not null,
    created_at timestamp(6) with time zone not null
);

create table whatsapp_sender (
    id                 bigint generated by default as identity primary key,
    sender_key         varchar(64) not null unique,
    faculty_short_code varchar(10),
    updated_at         timestamp(6) with time zone not null
);
